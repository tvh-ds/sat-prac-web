import assert from "node:assert/strict";
import { pathToFileURL, fileURLToPath } from "node:url";
import { mkdir } from "node:fs/promises";
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE_PATH ? pathToFileURL(process.env.PLAYWRIGHT_MODULE_PATH).href : "playwright");
const browser = await chromium.launch({ headless: true });
const base = "http://127.0.0.1:5173";
const user = { id: "11111111-1111-4111-8111-111111111111", email: "admin@example.invalid", aud: "authenticated", role: "authenticated", user_metadata: {}, app_metadata: {}, created_at: new Date().toISOString() };
const encode = x => Buffer.from(JSON.stringify(x)).toString("base64url");
const token = `${encode({ alg: "HS256" })}.${encode({ sub: user.id, exp: Math.floor(Date.now() / 1000) + 3600 })}.fixture`;
const session = { user, access_token: token, refresh_token: "fixture", expires_at: Math.floor(Date.now() / 1000) + 3600, expires_in: 3600, token_type: "bearer" };
const classId = "22222222-2222-4222-8222-222222222222";
const batch = (id, title, class_id = null) => ({ id, title, class_id, class_name: class_id ? "Class A" : null, assigned_at: new Date().toISOString(), timer_minutes: 20, question_count: 10, student_count: 2, completed_count: 1, avg_accuracy: 80, content_scope: "full_test" });
const practice = [batch("practice-a", "Class practice", classId), batch("practice-b", "Individual practice")];
const full = [batch("full-a", "Class full test", classId), batch("full-b", "Individual full test")];
const deck = { id: "deck-a", name: "SAT words", card_count: 20, student_count: 2, students_with_due: 1, students_done_today: 1, remaining_today: 5, reviewed_today: 8, students: [] };
const artifacts = new URL("../../tmp/assignments-review/", import.meta.url);
await mkdir(artifacts, { recursive: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const page = await context.newPage();
const errors = [], deletes = [], vocabQueries = [];
let failDelete = false;
page.on("pageerror", e => errors.push(e.message));
await page.addInitScript(({ session }) => localStorage.setItem("sb-wgkggknyndgaoyazdhdf-auth-token", JSON.stringify(session)), { session });
await page.route("**/*.supabase.co/**", async route => {
  const req = route.request(), url = new URL(req.url());
  assert.equal(url.hostname, "wgkggknyndgaoyazdhdf.supabase.co");
  const json = (body, status = 200) => route.fulfill({ status, contentType: "application/json", body: JSON.stringify(body) });
  if (url.pathname === "/auth/v1/user") return json(user);
  if (url.pathname === "/rest/v1/profiles") return json([{ id: user.id, role: "admin", full_name: "Admin" }]);
  if (url.pathname === "/rest/v1/admin_review_annotations") return json([]);
  if (req.method() === "DELETE") { deletes.push(url.pathname + url.search); return json(failDelete ? { error: "Delete failed. Please try again." } : { ok: true }, failDelete ? 500 : 200); }
  if (url.pathname.endsWith("/admin-classes")) return json({ classes: [{ id: classId, name: "Class A", student_ids: [] }] });
  if (url.pathname.endsWith("/admin-practice-assignments")) return json({ batches: practice });
  if (url.pathname.endsWith("/admin-tests/assignment-batches")) return json({ batches: full });
  if (url.pathname.endsWith("/admin-tests/assignment-batches/full-a")) return json({ batch: full[0], students: [] });
  if (url.pathname.endsWith("/admin-practice-assignments/practice-a")) return json({ batch: practice[0], students: [], questions: [] });
  if (url.pathname.includes("/admin-review-annotations")) return json({ annotations: [] });
  if (url.pathname.includes("/admin-vocab/assignments")) { vocabQueries.push(url.search); return json({ date: "2026-10-18", decks: [deck] }); }
  throw new Error(`Unexpected request ${req.url()}`);
});
try {
  await page.goto(`${base}/admin/assignments`);
  await page.getByRole("button", { name: "Delete assignment Class practice", exact: true }).waitFor();
  await page.getByLabel("Filter by class").selectOption(classId);
  assert.equal(await page.getByText("Individual practice", { exact: true }).count(), 0);
  await page.screenshot({ path: fileURLToPath(new URL("desktop.png", artifacts)), fullPage: true });
  await page.getByRole("button", { name: /Full-Length Test/ }).click();
  assert.equal(await page.getByLabel("Filter by class").inputValue(), classId);
  assert.equal(await page.getByText("Individual full test", { exact: true }).count(), 0);
  page.once("dialog", dialog => dialog.dismiss());
  await page.getByRole("button", { name: "Delete assignment Class full test", exact: true }).click();
  assert.equal(deletes.length, 0, "Cancel must not send delete");
  failDelete = true;
  page.once("dialog", dialog => dialog.accept());
  await page.getByRole("button", { name: "Delete assignment Class full test", exact: true }).click();
  await page.getByRole("alert").filter({ hasText: "Delete failed" }).waitFor();
  assert.equal(await page.getByRole("button", { name: "Delete assignment Class full test", exact: true }).count(), 1, "Failed deletion keeps row");
  failDelete = false;
  page.once("dialog", dialog => dialog.accept());
  await page.getByRole("button", { name: "Delete assignment Class full test", exact: true }).click();
  await page.getByText("No full-length test assignments match this class filter.").waitFor();
  await page.getByRole("button", { name: /Practice Set/ }).click();
  page.once("dialog", dialog => dialog.accept());
  await page.getByRole("button", { name: "Delete assignment Class practice", exact: true }).click();
  await page.getByText("No practice assignments match this class filter.").waitFor();
  await page.getByLabel("Filter by class").selectOption("individual");
  await page.getByText("Individual practice", { exact: true }).waitFor();
  await page.getByLabel("Filter by class").selectOption(classId);
  await page.getByRole("button", { name: "Vocabulary", exact: true }).click();
  await page.getByRole("button", { name: "Delete vocabulary assignment SAT words", exact: true }).waitFor();
  assert.ok(vocabQueries.at(-1).includes(classId));
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: fileURLToPath(new URL("mobile.png", artifacts)), fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), "No page overflow on mobile");
  page.once("dialog", dialog => dialog.accept());
  await page.getByRole("button", { name: "Delete vocabulary assignment SAT words", exact: true }).click();
  await page.getByText("No decks due today", { exact: true }).waitFor();
  assert.ok(deletes.at(-1).includes(`class_id=${classId}`), "Vocabulary delete retains class scope");
  for (const kind of ["full", "practice"]) {
    await page.goto(`${base}/admin/assignments/${kind}/${kind}-a`);
    const remove = page.getByRole("button", { name: "Delete assignment", exact: true });
    await remove.waitFor();
    const before = deletes.length;
    page.once("dialog", dialog => dialog.dismiss());
    await remove.click();
    assert.equal(deletes.length, before, "Detail cancel sends no delete");
    failDelete = true;
    page.once("dialog", dialog => dialog.accept());
    await remove.click();
    await page.getByRole("alert").filter({ hasText: "Delete failed" }).waitFor();
    assert.ok(page.url().includes(`${kind}-a`), "Detail remains open after failed deletion");
    failDelete = false;
    page.once("dialog", dialog => dialog.accept());
    await remove.click();
    await page.waitForURL(`${base}/admin/assignments${kind === "full" ? "?tab=full" : ""}`);
    assert.ok(deletes.at(-1).endsWith(kind === "full" ? "/admin-tests/assignment-batches/full-a" : "/admin-practice-assignments/practice-a"), "Detail deletes the selected batch");
  }
  assert.deepEqual(errors, []);
  console.log("PASS: class filters, list and detail deletion, cancellation, failure recovery, redirect, vocabulary class scope, desktop/mobile layout");
} finally { await browser.close(); }
